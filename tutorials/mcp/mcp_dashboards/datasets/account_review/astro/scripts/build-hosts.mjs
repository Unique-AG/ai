#!/usr/bin/env node
// Bundles the TypeScript host entries in src/host/ into the plain JS files that
// public/ serves, pulling in the shared host from helpers/astro/host/ via the
// @mcp-dashboards/host/* alias. esbuild reads that alias from tsconfig.json, so
// it needs no configuration here.
//
// The hosts used to live in public/ as hand-written JS. Because public/ is copied
// verbatim and never compiled, they could not import src/lib — so the
// data-unique-* interpreter was implemented twice, untyped, and live MCP
// responses were never validated. Building them from src/ instead means one
// typed implementation that shares the generated Zod schemas with the rest of
// the app.
//
// Astro copies all of public/ into every outDir, so the output is written per
// mode: `live` ships no host at all and gets an empty public/, keeping the
// platform artifact byte-for-byte zero-JS no matter what was built before it.
//
// Usage: node scripts/build-hosts.mjs [live|preview|live-local]   (all if omitted)
//
// esbuild comes in via Astro's own Vite dependency, so this adds no new package.
import { build } from "esbuild";
import { rmSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");

const HOSTS = {
  "mock-host": { entry: "src/host/mockHost.ts", modes: ["preview"] },
  "mcp-live-host": { entry: "src/host/liveHost.ts", modes: ["live-local"] },
};

const banner = `// AUTO-GENERATED by scripts/build-hosts.mjs — DO NOT EDIT.
// Source: src/host/ + helpers/astro/host/. Rebuild with: npm run hosts`;

const mode = process.argv[2] ?? process.env.DASHBOARD_MODE ?? null;
const wanted = Object.entries(HOSTS).filter(([, host]) => mode === null || host.modes.includes(mode));

// Anything not wanted for this mode must not be left behind in public/.
for (const name of Object.keys(HOSTS)) {
  if (!wanted.some(([wantedName]) => wantedName === name)) {
    rmSync(path.join(PUBLIC_DIR, `${name}.js`), { force: true });
  }
}

if (wanted.length === 0) {
  console.log(`No host script for mode ${mode} — public/ is empty by design.`);
  process.exit(0);
}

const built = await Promise.all(
  wanted.map(async ([name, host]) => {
    const result = await build({
      entryPoints: [path.join(ROOT, host.entry)],
      outfile: path.join(PUBLIC_DIR, `${name}.js`),
      bundle: true,
      // IIFE keeps these loadable as a classic <script src>, so the page stays a
      // single static document with no module graph.
      format: "iife",
      platform: "browser",
      target: ["es2020"],
      // These are dev-only hosts; stepping through them in devtools matters more
      // than a few KB.
      minify: false,
      sourcemap: false,
      legalComments: "none",
      banner: { js: banner },
      logLevel: "warning",
      metafile: true,
    });
    const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
    return `  public/${name}.js  ${(bytes / 1024).toFixed(1)} KB`;
  }),
);

console.log(`Built host scripts${mode ? ` for ${mode}` : ""}:`);
for (const line of built) console.log(line);
